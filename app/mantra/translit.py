"""Devanagari to Roman, by table.

OURS, NOT COPIED, and not generated by a model either. A transliteration is a mechanical mapping;
taking one from a source would be taking the source's work, and asking a model for one would make
every line a thing to check. A table is reviewable, deterministic, and wrong in the same way
everywhere - which is the kind of wrong that can be fixed once.

THE SCHEME IS READING-ROMAN, NOT IAST. Somebody searching "hanuman chalisa in english" wants to
READ the verse aloud from Latin letters; they do not want Hanumāna Cālīsā. So: no diacritics, no
vowel-length marks, and the conventional English spellings of names where they exist - Hanuman,
Shiva, Krishna - which a bare table cannot know and the override map below supplies.
"""
from __future__ import annotations

import re

# The independent vowels, then the consonants with their inherent 'a'.
VOWELS = {
    "अ": "a", "आ": "aa", "इ": "i", "ई": "ee", "उ": "u", "ऊ": "oo", "ऋ": "ri",
    "ए": "e", "ऐ": "ai", "ओ": "o", "औ": "au", "ॐ": "om",
}
MATRAS = {
    "ा": "aa", "ि": "i", "ी": "ee", "ु": "u", "ू": "oo",
    "ृ": "ri", "े": "e", "ै": "ai", "ो": "o", "ौ": "au",
}
CONSONANTS = {
    "क": "k", "ख": "kh", "ग": "g", "घ": "gh", "ङ": "n",
    "च": "ch", "छ": "chh", "ज": "j", "झ": "jh", "ञ": "n",
    "ट": "t", "ठ": "th", "ड": "d", "ढ": "dh", "ण": "n",
    "त": "t", "थ": "th", "द": "d", "ध": "dh", "न": "n",
    "प": "p", "फ": "ph", "ब": "b", "भ": "bh", "म": "m",
    "य": "y", "र": "r", "ल": "l", "व": "v", "ळ": "l",
    "श": "sh", "ष": "sh", "स": "s", "ह": "h",
    "क़": "q", "ख़": "kh", "ग़": "gh", "ज़": "z", "ड़": "r", "ढ़": "rh", "फ़": "f",
}
SIGNS = {"ं": "n", "ँ": "n", "ः": "h", "़": ""}
VIRAMA = "्"

#: NAMES PEOPLE ALREADY SPELL A CERTAIN WAY. A table gives "hanumaan"; every English page about him
#: says Hanuman, and a reader searching that spelling should find ours. Applied after the table, on
#: word boundaries, so it never rewrites the middle of another word.
CONVENTIONAL = {
    "hanumaan": "hanuman", "raam": "ram", "siita": "sita", "seeta": "sita",
    "krishn": "krishna", "shiv": "shiva", "ganesh": "ganesh", "gauree": "gauri",
    "lakshmee": "lakshmi", "durgaa": "durga", "kaalee": "kali", "vishnu": "vishnu",
    "brahmaa": "brahma", "saraswatee": "saraswati", "paarvatee": "parvati",
    "chaaleesaa": "chalisa", "aaratee": "aarti", "stotr": "stotra", "mantr": "mantra",
    "jai": "jai", "shree": "shri", "om": "om",
}
_WORD = re.compile(r"[a-z]+")


def _word(text: str) -> str:
    out: list[str] = []
    index = 0
    while index < len(text):
        char = text[index]
        nxt = text[index + 1] if index + 1 < len(text) else ""
        if char in CONSONANTS:
            out.append(CONSONANTS[char])
            if nxt == VIRAMA:                       # conjunct: no inherent vowel
                index += 2
                continue
            if nxt in MATRAS:
                out.append(MATRAS[nxt])
                index += 2
                continue
            if nxt in SIGNS:
                out.append("a" + SIGNS[nxt])
                index += 2
                continue
            out.append("a")                         # the inherent vowel
        elif char in VOWELS:
            out.append(VOWELS[char])
            if nxt in SIGNS:
                out.append(SIGNS[nxt])
                index += 2
                continue
        elif char in SIGNS:
            out.append(SIGNS[char])
        elif char in MATRAS:
            out.append(MATRAS[char])
        index += 1
    return "".join(out)


def romanise(text: str) -> str:
    """One pada in Latin letters, readable aloud.

    The trailing inherent vowel is dropped at the end of a word - Hindi does not pronounce it, and
    "raama" reads wrong to the person this is for.
    """
    words = []
    for token in text.split():
        core = _word(token)
        # DROP THE FINAL INHERENT VOWEL, which Hindi does not pronounce - but not when the word
        # would then end in two consonants. देवस्य gives "devasya"; cutting the vowel leaves
        # "devasy", which cannot be read aloud at all. Sanskrit keeps the vowel more often than
        # Hindi does, and these texts are a mix, so the readable rule is the one that applies.
        if len(core) > 2 and core.endswith("a") and not re.search(r"[bcdfghjklmnpqrstvwxyz]{2}a$",
                                                                 core):
            core = core[:-1]
        words.append(CONVENTIONAL.get(core, core))
    joined = " ".join(words)
    return _WORD.sub(lambda m: CONVENTIONAL.get(m.group(0), m.group(0)), joined).strip()
